# v3: 転換前にパラレル問題を止めるための質問。
#
# v2 の計測（2026-09-22, 11 問 380 点）で、parallel は「ですが」が読まれた
# 後に跳ね上がる事後検出器だと分かった（0.24〜0.44 → 0.67〜0.84）。
# 検出器としては優秀だが、早押しには使えない。転換語が出た時点では
# 既に押すかどうかを決めた後だからである。
#
# 実際、転換前に buzz が先に上がる:
#
#   20260821/27  26文字「…西を守っているのは白虎で」 buzz=0.82 parallel=0.33
#   20260821/5   16文字「…ハンガリーの首都です」    buzz=0.69 parallel=0.39
#
# どちらも parallel が 0.35 前後で、ゲートを素通りしてしまう。
#
# そこで着目を変える。パラレル問題の前半は必ず「A は X です」という平叙文で、
# まだ問いの形になっていない。転換語を待たずとも、今見えている文が
# 問いの本体に入っているかどうかは構文から判断できる。
# ---------------------------------------------------------------------------

#: 問いが始まったか。パラレル問題の前半を、転換語より前に弾くために使う。
#
# 「何でしょう」「どこ」などの疑問表現そのものを探しているのではない。
# 早押しクイズでは問いの本体が最後に来るため、平叙文で終わっている間は
# まだ問われる対象が確定していない、という構造を見ている。
ASKING: Final = {
    "type": "noul",
    "instructions": (
        "これは日本語の早押しクイズの問題文を、読み上げの途中まで書き起こしたものです。"
        "早押しクイズの問題文は、説明や前置きが続いた後に、最後へ問いの本体"
        "（「〜は何でしょう？」「〜はどこでしょう？」など）が来ます。"
        "今見えている範囲は、既に問いの本体に入っていますか。"
    ),
    "criteria": {
        "true": (
            "既に問いの本体に入っている。"
            "今見えている範囲で、何が問われているかが分かる"
        ),
        "false": (
            "まだ説明や前置きの途中である。平叙文が続いており、"
            "何が問われるかはこれから示される"
        ),
    },
}

#: v3。buzz と parallel は v2 のまま、asking を足す。
#
# parallel を残すのは、事後検出器としては有効であり、記録として
# 「転換があったか」を残せるため。押下判定には asking を使う。
QUESTIONS_V3: Final[dict[str, dict[str, object]]] = {
    "buzz": BUZZ_ACTION,
    "parallel": PARALLEL_SHIFT,
    "narrowed": NARROWED,
    "asking": ASKING,
}

VARIANTS["v3"] = QUESTIONS_V3
