# 質問文の改善案（variant）。
#
# 初回計測（2026-09-22, 5 問 249 点）で、上の定義に 3 つの問題が出た:
#
#   1. buzz は全文を読み切っても平均 0.84 までしか上がらず、上限が問題ごとに
#      違う（0.74〜0.92）。絶対値の固定閾値が使えない。
#   2. 人間が押せる位置（「芸術は爆発だ」など固有の手掛かりが出た時点）でも
#      buzz は 0.32〜0.66 と低い。buzz は「確定したか」ではなく
#      「情報がどれだけ積み上がったか」を測っている。
#   3. パラレル問題が 1 問も無い計測で parallel の平均が 0.296、
#      4 割の観測点が 0.35 を超えた。「前振りの途中か」という問い方が
#      「文がまだ続くか」を拾っている。
#
# そこで質問文を変えた案を置き、同じ問題セットで比較する。
# 選択は measure_buzz_curve.py の --variant で行う。
# ---------------------------------------------------------------------------

#: buzz の改善案。「絞り込めるか」ではなく「今の情報だけで答えられるか」を問う。
#
# 元の文面は状態（絞り込めているか）を問うており、情報量の多寡に引きずられた。
# 早押しで必要なのは行動の可否なので、「残りを聞かずに答えを言えるか」という
# 行動の形で問う。criteria も、答えが言えるかどうかで切る。
BUZZ_ACTION: Final = {
    "type": "noul",
    "instructions": (
        "これは日本語の早押しクイズの問題文を、読み上げの途中まで書き起こしたものです。"
        "あなたは早押しクイズの解答者です。"
        "ここで解答権を得た場合、問題文の残りを聞かずに、今見えている情報だけで"
        "正解を言い当てられますか。"
    ),
    "criteria": {
        "true": (
            "今見えている情報だけで正解を断定できる。"
            "固有名詞・異名・特徴的な引用など、答えを一つに決める手掛かりが既に出ている"
        ),
        "false": (
            "まだ答えを断定できない。ここで解答すると誤答になる可能性が高い"
        ),
    },
}

#: parallel の改善案。「途中か」ではなく「主題が入れ替わるか」を問う。
#
# 元の文面は「前振りの途中か」で、文の未完了性を拾っていた（文末に近づくほど
# 値が下がる挙動がそれを示す）。ここでは、今見えている話題が最終的に問われる
# 対象と一致するかを問い、転換の有無そのものを見る。
PARALLEL_SHIFT: Final = {
    "type": "noul",
    "instructions": (
        "これは日本語の早押しクイズの問題文を、読み上げの途中まで書き起こしたものです。"
        "早押しクイズには「A は X ですが、B は Y でしょう？」のように、"
        "最初に述べた話題とは別のものを最終的に問う形式があります。"
        "この問題文は、今見えている話題とは別のものが最終的に問われる形式ですか。"
    ),
    "criteria": {
        "true": (
            "今見えている話題は対比のために置かれたもので、"
            "最終的に問われるのはそれとは別の対象になる"
        ),
        "false": (
            "今見えている話題そのものについて問われる。対比の相手は登場しない"
        ),
    },
}

#: 改善案一式。元の定義と同じキーを使い、呼び出し側を変えずに差し替えられる。
QUESTIONS_V2: Final[dict[str, dict[str, object]]] = {
    "buzz": BUZZ_ACTION,
    "parallel": PARALLEL_SHIFT,
    "narrowed": NARROWED,
}

#: variant 名から質問定義を引く。
VARIANTS: Final[dict[str, dict[str, dict[str, object]]]] = {
    "v1": QUESTIONS,
    "v2": QUESTIONS_V2,
}


