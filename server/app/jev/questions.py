"""Jev へ投げる質問の定義。

1 リクエストに 3 問を混ぜて並列に評価させる。Jev は質問を増やしても応答時間が
ほぼ変わらないため（公式の "Speculative Fan-Out"）、押下判定に直接使わない
narrowed も同じ呼び出しに載せている。

質問を増やす場合はここへ足す。閾値の判断は client/router ではなく、
呼び出し側（jev-poc）が行う。サーバは観測値を返すだけに留める。
"""

from __future__ import annotations

from typing import Final

#: 押下判定。この確率が閾値を超えたら早押しする。
#
# noul（0〜1 の真偽確率）を使い、特徴ごとの score を並べる形は採らない。
# 「今押せるか」は複数の独立要素の合成ではなく単一の判断であり、
# 公式が分解を勧めているのは「1 つの質問が複数の独立要素を含む場合」である。
# 特徴を分解しても最後は「押すか」へ畳まれるうえ、閾値の調整対象が増える。
BUZZ: Final = {
    "type": "noul",
    "instructions": (
        "これは日本語の早押しクイズの問題文を、読み上げの途中まで書き起こしたものです。"
        "文の途中や単語の途中で切れていることがあります。"
        "この時点の情報だけで、この問題の答えを一つに絞り込めますか。"
    ),
    "criteria": {
        "true": (
            "答えを一つに特定できる。ここで早押しボタンを押して正答できる状態"
        ),
        "false": (
            "答えの候補が複数残っている。まだ情報が足りず、押すと誤答の恐れがある"
        ),
    },
}

#: パラレル問題の前振り検出。buzz から差し引いて使う。
#
# 「A は X ですが、B は Y でしょう？」形式は頻出で、自動早押しでは最大の事故要因。
# 「日本一高い山は富士山ですが、二番目に高い山は？」の前半では buzz が高く出るが、
# 押すと誤答になる。
#
# 「ですが」の文字列マッチでは防げない。確定ポイント（「…富士山」）は転換語より
# 前に現れるため、出現を待つ方式では間に合わない。読み上げ済みの部分の構文から
# 「この後に転換が来そうか」を推し量る必要があり、それは確率で答える問いになる。
PARALLEL: Final = {
    "type": "noul",
    "instructions": (
        "これは日本語の早押しクイズの問題文を、読み上げの途中まで書き起こしたものです。"
        "早押しクイズには「A は X ですが、B は Y でしょう？」のように、"
        "前半で一つの話題を振ってから後半で別のことを問う形式（パラレル問題）があります。"
        "この書き起こしは、その前半の振り部分の途中ですか。"
    ),
    "criteria": {
        "true": (
            "前振りの途中である。この後に「ですが」などで話題が転換し、"
            "本当に問われるのは別のことになる"
        ),
        "false": (
            "転換の予兆がない。単一の問いであるか、既に転換した後の本題に入っている"
        ),
    },
}

#: 候補の絞られ具合。押下判定には使わず、記録と閾値調整に使う。
#
# buzz が 0.6 で押さなかったとき、「候補が広かったのか、狭いのに確信が持てなかったのか」
# が残らないと閾値を動かす根拠が作れない。
#
# score の値は criteria の段階数に依存し、0〜1 ではない。4 段階なので 0〜3 の連続値。
NARROWED: Final = {
    "type": "score",
    "instructions": (
        "これは日本語の早押しクイズの問題文を、読み上げの途中まで書き起こしたものです。"
        "この時点で、答えの候補がどこまで絞り込まれているかを評価してください。"
    ),
    "criteria": [
        "話題の分野すら定まらない",
        "分野は分かるが、候補が多数ある",
        "候補が数個まで絞られた",
        "答えが一つに確定した",
    ],
}

#: 1 リクエストで投げる質問。キーが応答の answers のキーになる。
QUESTIONS: Final[dict[str, dict[str, object]]] = {
    "buzz": BUZZ,
    "parallel": PARALLEL,
    "narrowed": NARROWED,
}

#: narrowed の段階数。score の値域（0 〜 LEVELS-1）を呼び出し側へ伝えるため。
NARROWED_LEVELS: Final = len(NARROWED["criteria"])
